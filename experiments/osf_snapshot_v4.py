"""Build OSF snapshot v4: v3's five documents + the adopted Addendum A.

v4 is generated, not hand-edited: the five prior documents' provenance
rows are carried from v3 unchanged, and each file's CURRENT sha256 is
asserted against its v3 row before anything is written — if any frozen
document changed on disk since its snapshot, this refuses to run.
Document 6 is PREREGISTRATION_AMENDMENT_2_ADDENDUM_A.md at its adoption
commit, passed on the command line.
"""
import hashlib
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
V3 = ROOT / "results" / "osf_preregistration_snapshot_v3.md"
V4 = ROOT / "results" / "osf_preregistration_snapshot_v4.md"

DOCS_V3 = [
    "PREREGISTRATION.md",
    "PREREGISTRATION_AMENDMENT_1.md",
    "PREREGISTRATION_AMENDMENT_1_ADDENDUM_A.md",
    "PREREGISTRATION_AMENDMENT_2.md",
    "PREREGISTRATION_AMENDMENT_3.md",
]
DOC6 = "PREREGISTRATION_AMENDMENT_2_ADDENDUM_A.md"


def sha(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main():
    adoption_commit = sys.argv[1]
    head = subprocess.run(["git", "rev-parse", "--short", "HEAD"],
                          capture_output=True, text=True, cwd=ROOT,
                          check=True).stdout.strip()
    v3_text = V3.read_text()
    rows = dict(re.findall(
        r"\| \d+ \| `([A-Z0-9_.]+)` \| `([0-9a-f]+)` \|", v3_text))
    table = []
    for i, doc in enumerate(DOCS_V3, 1):
        m = re.search(
            rf"\| {i} \| `{re.escape(doc)}` \| `([0-9a-f]+)` \| `([0-9a-f]{{64}})` \|",
            v3_text)
        assert m, f"{doc} missing from the v3 table"
        commit, recorded = m.group(1), m.group(2)
        current = sha(ROOT / doc)
        assert current == recorded, (
            f"{doc} changed on disk since v3 ({current} != {recorded}); "
            "a frozen document must never change — refusing to build v4")
        table.append((doc, commit, recorded))
    table.append((DOC6, adoption_commit, sha(ROOT / DOC6)))

    out = [
        "# DOPPLER pre-registration — OSF timestamp snapshot, v4\n",
        "Prepared 2026-07-28 for external timestamping. **Frozen copy. "
        "Do not edit.**\n",
        "This supersedes `results/osf_preregistration_snapshot_v3.md`, which "
        "covered the\nfirst five governance documents; v3, v2 and the original "
        "are all kept\nverbatim forever. v4 adds the sixth: the Stage 2 "
        "bar-lock addendum, ADOPTED\n2026-07-28 after its pre-committed "
        "parameter-5 gate passed on the second\ntranche (the first tranche "
        "FAILED and the pre-committed iteration is part of\nthe addendum's "
        "own record).\n",
        "Each document below is preceded by a provenance header giving the "
        "commit it was\nadopted in and the sha256 of the file at that commit. "
        "Nothing was added, removed,\nor reworded inside any document.\n",
        "**The OSF upload itself has not happened, and it remains on the "
        "owner.** Until it\ndoes, \"pre-registered\" means \"committed to git "
        "before the data was touched\".\n",
        "| # | document | adopted in commit | sha256 |",
        "|---|---|---|---|",
    ]
    for i, (doc, commit, digest) in enumerate(table, 1):
        out.append(f"| {i} | `{doc}` | `{commit}` | `{digest}` |")
    out.append("\nLater documents override earlier ones where they conflict.\n")
    out.append(f"Generated by `experiments/osf_snapshot_v4.py` at repo HEAD "
               f"`{head}`.\n")
    for i, (doc, commit, digest) in enumerate(table, 1):
        out.append("\n---\n")
        out.append(f"<!-- SNAPSHOT DOCUMENT {i} OF {len(table)} -->\n")
        out.append(f"**Provenance — document {i} of {len(table)}:** `{doc}`, "
                   f"adopted in commit `{commit}`, sha256 `{digest}`. "
                   f"Verbatim below.\n")
        out.append((ROOT / doc).read_text().rstrip())
    V4.write_text("\n".join(out) + "\n")
    print(f"wrote {V4.relative_to(ROOT)}: {len(table)} documents")
    for i, (doc, commit, digest) in enumerate(table, 1):
        print(f"  {i}. {doc} @ {commit} {digest[:12]}…")


if __name__ == "__main__":
    main()
